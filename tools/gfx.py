#!/usr/bin/env python3
"""gfx.py - converts art/*.txt into data/*.asm and preview PNGs.

  sprites.txt -> data/sprites.asm : masked, pre-shifted (4 shifts: 0,2,4,6 px) frames
                                    + pointer tables SPR_<name> (4 DW each)
  tiles.txt   -> data/tiles.asm   : 16x16 tiles, 32 bitmap bytes + 4 attrs, flag table,
                                    and art/tilechars.py (char -> index map for maptool)
  udg.txt     -> data/udg.asm     : 8x8 HUD / frame graphics
  tune        -> data/tune.asm    : menu tune (period,length) pairs for engine/sound.asm
Run from the miremare/ directory."""
import os, sys
from PIL import Image

INK = dict(k=0, b=1, r=2, m=3, g=4, c=5, y=6, w=7)
FLAG = dict(solid=1, slow=2, sink=4, item=8, walk=0)

def parse_blocks(path, kw):
    blocks, cur = [], None
    for line in open(path):
        line = line.rstrip('\n')
        if line.startswith('# ') or line == '#': continue
        if line.startswith(kw + ' ') or line.startswith('MIRROR '):
            cur = [line.split(), []]; blocks.append(cur)
            if line.startswith('MIRROR '): cur = None
            continue
        if cur is not None and line.strip():
            cur[1].append(line)
    return blocks

def dbs(label, data, per=16):
    out = [label + ':'] if label else []
    for i in range(0, len(data), per):
        out.append('        DEFB ' + ','.join('$%02X' % b for b in data[i:i+per]))
    return out

# ---------------------------------------------------------------- sprites
def sprite_frames():
    frames = {}
    order = []
    for hdr, rows in parse_blocks('art/sprites.txt', 'SPRITE'):
        if hdr[0] == 'MIRROR':
            name, src = hdr[1], hdr[2]
            frames[name] = [r[::-1] for r in frames[src]]; order.append(name); continue
        name = hdr[1]; w, h = map(int, hdr[2].split('x'))
        if len(rows) != h: sys.exit('%s: %d rows, want %d' % (name, len(rows), h))
        for i, r in enumerate(rows):
            if len(r) != w: sys.exit('%s row %d: width %d, want %d' % (name, i, len(r), w))
        frames[name] = rows; order.append(name)
    return frames, order

def shifted(rows, shift):
    """returns list of rows, each a list of (mask,data) byte pairs, width+1 bytes."""
    h, w = len(rows), len(rows[0])
    ink = [[rows[y][x] == '#' for x in range(w)] for y in range(h)]
    opq = [[rows[y][x] in '#-' for x in range(w)] for y in range(h)]
    # keyline: 4-neighbours of ink become opaque black
    key = [[opq[y][x] or any(0 <= y+dy < h and 0 <= x+dx < w and ink[y+dy][x+dx]
            for dx, dy in ((1,0),(-1,0),(0,1),(0,-1))) for x in range(w)] for y in range(h)]
    nb = w // 8 + 1
    out = []
    for y in range(h):
        row = []
        for b in range(nb):
            m = d = 0
            for bit in range(8):
                x = b*8 + bit - shift
                inside = 0 <= x < w
                m = (m << 1) | (0 if inside and key[y][x] else 1)
                d = (d << 1) | (1 if inside and ink[y][x] else 0)
            row.append((m, d))
        out.append(row)
    return out

def build_sprites():
    frames, order = sprite_frames()
    lines = ['; generated by tools/gfx.py from art/sprites.txt - do not edit',
             '; frame data: rows x (W/8+1) bytes x (mask,data); mask 1 = keep screen']
    total = 0
    for name in order:
        rows = frames[name]
        if not name.startswith(('sab_', 'spark', 'clod')): continue
        lines.append('SPR_%s:' % name)
        lines.append('        DEFW ' + ','.join('%s_s%d' % (name, s) for s in range(4)))
    for name in order:
        rows = frames[name]
        if not name.startswith(('sab_', 'spark', 'clod')):
            # runtime-shifted sprite: unshifted rows x (W/8) x (mask,data)
            sh = shifted(rows, 0)
            data = [v for row in sh for pair in row[:-1] for v in pair]
            total += len(data)
            lines += dbs('SPR_%s' % name, data)
            continue
        for s in range(4):
            data = [v for row in shifted(rows, s*2) for pair in row for v in pair]
            total += len(data)
            lines += dbs('%s_s%d' % (name, s), data)
    # Mare cell-occupancy: for each frame (a,b,la,lb) and even x shift, which of
    # the 5x3 character cells her mask (shape + keyline) touches.  On the Mere
    # those cells are cleared to black and given her own ink before she is drawn,
    # so she is white on a cell-aligned shadow - never sharing a cell with a lily.
    lines.append('mare_occ:')
    for name in ('mare_a', 'mare_b', 'mare_la', 'mare_lb'):
        ws = []
        for sh in (0, 2, 4, 6):
            rr = shifted(frames[name], sh); bits = 0
            for cy in range(3):
                for cx in range(5):
                    if any(rr[y][cx][0] != 0xFF for y in range(cy * 8, cy * 8 + 8)): bits |= 1 << (cy * 5 + cx)
            ws.append('$%04X' % bits)
        lines.append('        DEFW ' + ','.join(ws) + '   ; ' + name)
    open('data/sprites.asm', 'w').write('\n'.join(lines) + '\n')
    # preview sheet
    sc = 4
    img = Image.new('RGB', (len(order) * 36 * sc, 28 * sc), (40, 40, 40))
    for i, name in enumerate(order):
        rows = frames[name]
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                c = {'#': (255, 255, 255), '-': (0, 0, 0)}.get(ch)
                if c:
                    for yy in range(sc):
                        for xx in range(sc):
                            img.putpixel((i*36*sc + 2*sc + x*sc + xx, 2*sc + y*sc + yy), c)
    img.save('build/sprites_preview.png')
    return total, order

# ---------------------------------------------------------------- tiles
PAL = [(0,0,0),(0,0,0xD7),(0xD7,0,0),(0xD7,0,0xD7),(0,0xD7,0),(0,0xD7,0xD7),(0xD7,0xD7,0),(0xD7,0xD7,0xD7),
       (0,0,0),(0,0,0xFF),(0xFF,0,0),(0xFF,0,0xFF),(0,0xFF,0),(0,0xFF,0xFF),(0xFF,0xFF,0),(0xFF,0xFF,0xFF)]

def attr_of(code):
    a = INK[code.lower()]
    if code.isupper(): a |= 0x40
    return a

def parse_tiles():
    tiles = []
    for hdr, rows in parse_blocks('art/tiles.txt', 'TILE'):
        # header: TILE <char> name flags inks ; char may be a quoted space
        line = ' '.join(hdr)
        if line.startswith("TILE ' '"):
            ch = ' '; rest = line[len("TILE ' '"):].split()
        else:
            ch = hdr[1]; rest = hdr[2:]
        name, flags, inks = rest
        rows = [r.ljust(16, '.')[:16] for r in rows]
        if len(rows) != 16: sys.exit('tile %s: %d rows' % (name, len(rows)))
        tiles.append(dict(ch=ch, name=name, flags=FLAG[flags], attrs=[attr_of(c) for c in inks.split(',')], rows=rows))
    return tiles

def build_tiles():
    tiles = parse_tiles()
    lines = ['; generated by tools/gfx.py from art/tiles.txt - do not edit',
             '; per tile: 16 rows x 2 bytes, then attrs TL,TR,BL,BR']
    for i, t in enumerate(tiles):
        lines.append('TILE_%s EQU %d' % (t['name'].upper(), i))
    lines.append('NUM_TILES EQU %d' % len(tiles))
    lines.append('tile_gfx:')
    for t in tiles:
        data = []
        for r in t['rows']:
            for half in (r[:8], r[8:]):
                data.append(int(''.join('1' if c == '#' else '0' for c in half), 2))
        lines += dbs(None, data + t['attrs'])
    lines += dbs('tile_flags', [t['flags'] for t in tiles])
    open('data/tiles.asm', 'w').write('\n'.join(lines) + '\n')
    with open('art/tilechars.py', 'w') as f:
        f.write('# generated by gfx.py\nTILES = %r\n' % [(t['ch'], t['name'], t['flags'], t['attrs'], t['rows']) for t in tiles])
    return tiles

# ---------------------------------------------------------------- udg
def build_udg():
    lines = ['; generated by tools/gfx.py from art/udg.txt']
    for hdr, rows in parse_blocks('art/udg.txt', 'UDG'):
        data = [int(''.join('1' if c == '#' else '0' for c in r[:8]), 2) for r in rows]
        lines += dbs('UDG_' + hdr[1], data)
    open('data/udg.asm', 'w').write('\n'.join(lines) + '\n')

# ---------------------------------------------------------------- tune
NOTES = {'C':0,'C#':1,'D':2,'D#':3,'E':4,'F':5,'F#':6,'G':7,'G#':8,'A':9,'A#':10,'B':11}
# An original eerie fen air in A minor (not a quotation of any existing tune).
TUNE = ("A5:2 C6:2 E6:2 A6:4 G6:2 E6:2 F6:4 E6:2 D6:2 E6:6 R:2 "
        "C6:2 D6:2 E6:2 G6:4 F6:2 D6:2 E6:4 C6:2 B5:2 A5:8")
def build_tune():
    out = []
    for tok in TUNE.split():
        n, l = tok.split(':'); l = int(l)
        dur = 0.09 * l
        if n == 'R':
            out += [0, max(1, int(l * 3))]; continue
        name, octv = n[:-1], int(n[-1])
        f = 440.0 * 2 ** ((NOTES[name] - 9 + 12 * (octv - 4)) / 12)
        d = round((3500000 / (2 * f) - 50) / 13)     # djnz half-period loop
        assert 1 <= d <= 255, (n, d)
        cyc = int(f * 2 * dur)                       # half cycles
        # engine plays notes as E=255-limited chunks: store count/256 hi + lo
        out += [d, cyc & 0xFF, cyc >> 8]
    lines = ['; generated by tools/gfx.py - menu tune: period, halfcycles(lo,hi); period 0 = rest(len)']
    # normalise rest records to 3 bytes too
    norm, i = [], 0
    toks = TUNE.split(); j = 0
    data = []
    for tok in toks:
        n, l = tok.split(':'); l = int(l)
        if n == 'R': data += [0, l * 2, 0]
        else:
            name, octv = n[:-1], int(n[-1])
            f = 440.0 * 2 ** ((NOTES[name] - 9 + 12 * (octv - 4)) / 12)
            d = round((3500000 / (2 * f) - 50) / 13)
            cyc = int(f * 2 * 0.09 * l)
            data += [d, cyc & 0xFF, cyc >> 8]
    data += [0xFF]
    lines += dbs('menu_tune', data)
    open('data/tune.asm', 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    os.makedirs('build', exist_ok=True)
    total, order = build_sprites()
    tiles = build_tiles()
    build_udg(); build_tune()
    print('sprites: %d frames, %d bytes; tiles: %d' % (len(order), total, len(tiles)))
