"""Writes data/messages.asm: the bridle rhymes and other message boxes."""
MSGS = {
 'msg_bit':     ['THE BIT OF IRON', 'COLD AND OLD', 'SHALL STILL HER MOUTH', 'AND CHECK HER BOLD'],
 'msg_rein':    ['THE REIN OF RUSH', 'FROM ROOT AND WEED', 'SHALL TURN HER HEAD', 'AND SLOW HER SPEED'],
 'msg_head':    ['THE HEADSTALL WOVE', 'IN ABBEY STONE', 'SHALL CROWN THE MARE', 'THAT RIDES ALONE'],
 'msg_buckle':  ['THE BUCKLE BRIGHT', 'FROM PEAT AND BONE', 'SHALL BIND THE WHOLE', 'WHEN ALL ARE SHOWN'],
 'msg_whole':   ['THE BRIDLE WHOLE', 'IS IN YOUR HAND', 'SEEK THE MARE', "ON MARE'S ISLE LAND"],
 'msg_lantern': ['A LANTERN FOUND', 'TO LIGHT THE DARK', 'BY NIGHT THE SPIRIT', 'DOORS WILL PART'],
 'msg_key':     ['THE ABBEY KEY', 'OF RUSTED IRON', 'THE CRYPT LIES OPEN', 'BENEATH THE STONE'],
 'msg_lever':   ['THE LEVER GROANS', 'THE WATERS FALL', 'THE CAUSEWAY RISES', 'ACROSS THE MERE'],
}
ATTR = [0x46, 0x46, 0x45, 0x45]
ROWS = [9, 10, 13, 14]
out = ['; generated by tools/messages.py']
for name, lines in MSGS.items():
    out.append(name + ':')
    out.append('        DEFB 1,8,4,2,$42,"' + '-' * 24 + '"')
    for r, a, t in zip(ROWS, ATTR, lines):
        assert len(t) <= 24, t
        out.append('        DEFB 1,%d,%d,2,$%02X,"%s"' % (r, 4 + (24 - len(t)) // 2, a, t))
    out.append('        DEFB 1,16,4,2,$42,"' + '-' * 24 + '",0')
open('data/messages.asm', 'w').write('\n'.join(out) + '\n')
