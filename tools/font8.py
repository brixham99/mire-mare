#!/usr/bin/env python3
"""font8.py - art/font8.txt (Mire Mare's own 8x8 font, chars 32-127) ->
data/font.asm (768 bytes, label font8).  Optional: font8.py --png out.png
writes a 16x6 preview sheet.  The game no longer reads the ROM character set."""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load():
    glyphs, cur = {}, None
    for line in open(os.path.join(ROOT, 'art/font8.txt')):
        line = line.rstrip('\n')
        if line.startswith(';') or not line.strip(): continue
        if line.startswith('= '):
            k = line[2:]
            cur = int(k) if len(k) > 1 else ord(k)
            assert 32 <= cur <= 127 and cur not in glyphs, line
            glyphs[cur] = []; continue
        glyphs[cur].append(line)
    out = bytearray()
    for c in range(32, 128):
        rows = glyphs.get(c)
        assert rows is not None, 'missing glyph %d' % c
        assert len(rows) <= 8 and len({len(r) for r in rows}) <= 1, 'glyph %d' % c
        w = len(rows[0]) if rows else 6; assert w in (6, 7), 'glyph %d width' % c
        for r in rows + ['.' * w] * (8 - len(rows)):   # 6 wide -> cols 1-6, 7 wide -> cols 0-6
            out.append(int(r.replace('#', '1').replace('.', '0'), 2) << 1)
    return bytes(out)

def main():
    f = load()
    with open(os.path.join(ROOT, 'data/font.asm'), 'w') as o:
        o.write('; data/font.asm - generated by tools/font8.py from art/font8.txt\n'
                '; Mire Mare 8x8 font, chars 32-127 (96 x 8 = 768 bytes)\nfont8:\n')
        for c in range(96):
            o.write('        DEFB %s   ; %d\n' % (','.join('$%02X' % b for b in f[c*8:c*8+8]), c + 32))
    if '--png' in sys.argv:
        from PIL import Image
        im = Image.new('1', (16 * 8, 6 * 8))
        for c in range(96):
            for y in range(8):
                for x in range(8):
                    if f[c*8+y] & (0x80 >> x): im.putpixel(((c % 16) * 8 + x, (c // 16) * 8 + y), 1)
        im.resize((im.width * 4, im.height * 4)).save(sys.argv[sys.argv.index('--png') + 1])
    print('font8: 96 glyphs, %d bytes' % len(f))

if __name__ == '__main__':
    main()
