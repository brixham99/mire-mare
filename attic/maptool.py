#!/usr/bin/env python3
"""maptool.py - art/map.txt -> data/rooms.asm (+ build/map_preview.png).

Room format (per room, pointed to by room_table):
    DEFW rle_ptr
    3 x (type, x, y)   enemy spawns, type $FF = none   (x even, pixels; y pixels)
    DEFB start_x, start_y  ($FF if not the start room)
RLE: byte < $80 = literal tile index; $80|n, t = n copies of tile t (n>=3).
Validates: every room 16x11, outer world edge closed, exits between neighbours
match exactly, at most one gem / quest item per room, at most 3 enemies."""
import os, sys
sys.path.insert(0, 'art')
from tilechars import TILES
from PIL import Image

RW, RH = 16, 11
ENEMY = {'W': 0, 'D': 1, 'A': 2}
idx = {t[0]: i for i, t in enumerate(TILES)}
flags = [t[2] for t in TILES]
SOLID, GEM, QUEST = 1, 8, 16

lines = [l.rstrip('\n') for l in open('art/map.txt') if not l.startswith('#')]
lines = [l.replace('|', '') for l in lines if not set(l) <= set('-')]
H = len(lines); W = max(len(l) for l in lines)
lines = [l.ljust(W) for l in lines]
MW, MH = W // RW, H // RH
assert W == MW * RW and H == MH * RH, (W, H)

rooms, errors = [], []
for ry in range(MH):
    for rx in range(MW):
        grid, ens, start = [], [], None
        for y in range(RH):
            row = []
            for x in range(RW):
                c = lines[ry*RH + y][rx*RW + x]
                if c in ENEMY: ens.append((ENEMY[c], x*16, y*16)); c = ' '
                elif c == 'P': start = (x*16, y*16); c = ' '
                if c not in idx: errors.append('room %d,%d: unknown tile %r' % (rx, ry, c)); c = ' '
                row.append(idx[c])
            grid.append(row)
        rooms.append(dict(grid=grid, ens=ens, start=start, rx=rx, ry=ry))

def solid(r, x, y): return flags[r['grid'][y][x]] & SOLID
for r in rooms:
    n = sum(1 for row in r['grid'] for t in row if flags[t] & (GEM | QUEST))
    if n > 1: errors.append('room %d,%d has %d items' % (r['rx'], r['ry'], n))
    if len(r['ens']) > 3: errors.append('room %d,%d has >3 enemies' % (r['rx'], r['ry']))
    rx, ry = r['rx'], r['ry']
    for y in range(RH):
        for side, x, nb in (('W', 0, (rx-1, ry)), ('E', RW-1, (rx+1, ry))):
            if not solid(r, x, y):
                if not (0 <= nb[0] < MW): errors.append('room %d,%d open to world edge %s row %d' % (rx, ry, side, y)); continue
                o = rooms[nb[1]*MW + nb[0]]
                if solid(o, RW-1-x, y): errors.append('room %d,%d %s exit row %d blocked in neighbour' % (rx, ry, side, y))
    for x in range(RW):
        for side, y, nb in (('N', 0, (rx, ry-1)), ('S', RH-1, (rx, ry+1))):
            if not solid(r, x, y):
                if not (0 <= nb[1] < MH): errors.append('room %d,%d open to world edge %s col %d' % (rx, ry, side, x)); continue
                o = rooms[nb[1]*MW + nb[0]]
                if solid(o, x, RH-1-y): errors.append('room %d,%d %s exit col %d blocked in neighbour' % (rx, ry, side, x))
if errors:
    print('\n'.join(errors)); sys.exit(1)

def rle(seq):
    out, i = [], 0
    while i < len(seq):
        j = i
        while j < len(seq) and seq[j] == seq[i] and j - i < 127: j += 1
        n = j - i
        if n >= 3: out += [0x80 | n, seq[i]]; i = j
        else: out.append(seq[i]); i += 1
    return out

asm = ['; generated by tools/maptool.py from art/map.txt - do not edit',
       'MAP_W EQU %d' % MW, 'MAP_H EQU %d' % MH, 'NUM_ROOMS EQU %d' % len(rooms)]
total = 0; start_room = None
asm.append('room_table:')
asm.append('        DEFW ' + ','.join('room_%d' % i for i in range(len(rooms))))
for i, r in enumerate(rooms):
    flat = [t for row in r['grid'] for t in row]
    data = rle(flat)
    total += len(data) + 12
    ens = r['ens'] + [(0xFF, 0, 0)] * (3 - len(r['ens']))
    st = r['start'] or (0xFF, 0xFF)
    if r['start']: start_room = i
    asm.append('room_%d:   ; (%d,%d)  rle %d bytes' % (i, r['rx'], r['ry'], len(data)))
    asm.append('        DEFW room_%d_rle' % i)
    asm.append('        DEFB ' + ','.join('$%02X' % v for e in ens for v in e))
    asm.append('        DEFB $%02X,$%02X' % st)
    asm.append('room_%d_rle:' % i)
    for k in range(0, len(data), 16):
        asm.append('        DEFB ' + ','.join('$%02X' % b for b in data[k:k+16]))
asm.insert(4, 'START_ROOM EQU %d' % start_room)
open('data/rooms.asm', 'w').write('\n'.join(asm) + '\n')

# preview, with real tile colours
PAL = [(0,0,0),(0,0,0xD7),(0xD7,0,0),(0xD7,0,0xD7),(0,0xD7,0),(0,0xD7,0xD7),(0xD7,0xD7,0),(0xD7,0xD7,0xD7)]
def col(a):
    c = PAL[a & 7]
    return tuple(min(255, int(v * (255/0xD7))) for v in c) if a & 0x40 else c
img = Image.new('RGB', (MW*256 + (MW-1)*4, MH*176 + (MH-1)*4), (90, 90, 90))
for r in rooms:
    ox, oy = r['rx']*260, r['ry']*180
    for ty in range(RH):
        for tx in range(RW):
            t = TILES[r['grid'][ty][tx]]
            for y in range(16):
                for x in range(16):
                    a = t[3][(y//8)*2 + x//8]
                    img.putpixel((ox+tx*16+x, oy+ty*16+y), col(a) if t[4][y][x] == '#' else (0,0,0))
img.save('build/map_preview.png')
print('rooms: %d (%dx%d), %d bytes incl. headers, start room %s' % (len(rooms), MW, MH, total, start_room))
